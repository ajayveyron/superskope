import { identities } from './group-actions.mjs';

export const memoryLimits = { recentExchanges:8, recentCharacters:32000, summaryExchanges:12, summaryCharacters:12000, retentionDays:30, clarificationMinutes:10 };
export const memoryIdentity = person => {
  const ids=identities(person);
  return ids.find(id=>id.endsWith('@c.us'))||ids[0];
};
const parse = (value,fallback) => {try{return JSON.parse(value)||fallback;}catch{return fallback;}};
const excerpt = text => typeof text==='string' ? text.length>300 ? text.slice(0,300)+' [excerpt; remainder omitted]' : text : '';

// Summaries are extracted from the execution ledger, never generated by a model.
// Requested, completed, failed, unknown and unattempted actions remain distinct.
function exchange(row,now) {
  const audit=parse(row.result,{}),results=audit.results||[];
  return {
    at:row.created_at,request:row.request,state:row.state,
    clarificationOpen:row.state==='clarification'&&now-Date.parse(row.created_at)<memoryLimits.clarificationMinutes*60000,
    reply:audit.message||audit.error||'',people:parse(row.people,[]),
    actions:(audit.plan||[]).map((action,i)=>{
      const stopped=results.slice(0,i).some(result=>result.state!=='completed');
      const state=results[i]?.state||(stopped?'not-run':['unknown','processing'].includes(row.state)?'unknown':'not-run');
      const {data,...safeAction}=action;
      return {...safeAction,state,...(results[i]?.error?{error:results[i].error}:{})};
    }),
  };
}
function compact(turn) {
  return {at:turn.at,requestExcerpt:excerpt(turn.request),replyExcerpt:excerpt(turn.reply),state:turn.state,actions:turn.actions,people:turn.people};
}
function bounded(entries,count,characters) {
  const result=[];let size=2;
  for(const entry of entries.slice(-count).reverse()){
    const n=JSON.stringify(entry).length+1;
    if(size+n>characters)break;
    result.unshift(entry);size+=n;
  }
  return result;
}

export function createConversationMemory({db,now=()=>new Date()}) {
  db.exec(`CREATE TABLE IF NOT EXISTS conversation_turns (
    command_id TEXT PRIMARY KEY, account_id TEXT NOT NULL, group_id TEXT NOT NULL, actor TEXT NOT NULL,
    created_at TEXT NOT NULL, request TEXT NOT NULL, people TEXT NOT NULL DEFAULT '[]');
    CREATE INDEX IF NOT EXISTS conversation_scope ON conversation_turns(account_id,group_id,actor,created_at);
    CREATE TABLE IF NOT EXISTS conversation_summaries (
    account_id TEXT NOT NULL, group_id TEXT NOT NULL, actor TEXT NOT NULL, entries TEXT NOT NULL,
    PRIMARY KEY(account_id,group_id,actor));`);
  const params=scope=>[scope.account,scope.group,scope.actor];
  function read(scope) {
    const cutoff=new Date(now().getTime()-memoryLimits.retentionDays*86400000).toISOString();
    // Removes only conversational context; the existing command audit is retained.
    db.prepare('DELETE FROM conversation_turns WHERE created_at<?').run(cutoff);
    db.prepare("DELETE FROM conversation_summaries WHERE json_extract(entries,'$[#-1].at')<?").run(cutoff);
    const rows=db.prepare(`SELECT t.*,c.state,c.result FROM conversation_turns t JOIN commands c ON c.id=t.command_id
      WHERE t.account_id=? AND t.group_id=? AND t.actor=? ORDER BY t.created_at,t.rowid`).all(...params(scope));
    const all=rows.map(row=>exchange(row,now().getTime()));
    for(const [i,turn] of all.entries())turn.clarificationOpen=turn.clarificationOpen&&i===all.length-1;
    const recent=bounded(all,memoryLimits.recentExchanges,memoryLimits.recentCharacters);
    const old=all.slice(0,all.length-recent.length);
    const stored=db.prepare('SELECT entries FROM conversation_summaries WHERE account_id=? AND group_id=? AND actor=?').get(...params(scope));
    const summary=bounded([...parse(stored?.entries,[]).filter(entry=>entry.at>=cutoff),...old.map(compact)],memoryLimits.summaryExchanges,memoryLimits.summaryCharacters);
    // Compaction and removal are atomic, including if the process stops here.
    db.exec('BEGIN');
    try{
      db.prepare(`INSERT INTO conversation_summaries VALUES (?,?,?,?) ON CONFLICT(account_id,group_id,actor) DO UPDATE SET entries=excluded.entries`).run(...params(scope),JSON.stringify(summary));
      for(const row of rows.slice(0,old.length))db.prepare('DELETE FROM conversation_turns WHERE command_id=?').run(row.command_id);
      db.exec('COMMIT');
    }catch(e){db.exec('ROLLBACK');throw e;}
    return {summary,recent};
  }
  function begin(scope,{id,created_at},request) {
    db.prepare('INSERT OR IGNORE INTO conversation_turns(command_id,account_id,group_id,actor,created_at,request) VALUES (?,?,?,?,?,?)').run(id,...params(scope),created_at,request);
  }
  function people(id,values) {
    db.prepare('UPDATE conversation_turns SET people=? WHERE command_id=?').run(JSON.stringify(values),id);
  }
  return {read,begin,people};
}
