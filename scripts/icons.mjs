// Keep the shipped dashboard independent of npm and external icon CDNs.
import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const names = {
  home: 'house', chat: 'chat-circle-dots', phone: 'phone', ticket: 'ticket',
  chart: 'chart-line', list: 'list-bullets', megaphone: 'megaphone',
  contacts: 'address-book', media: 'images', sparkles: 'sparkle', rules: 'flow-arrow',
  logs: 'list-checks', settings: 'gear', search: 'magnifying-glass',
  refresh: 'arrows-clockwise', help: 'question', download: 'download-simple',
  bell: 'bell-slash', sun: 'sun', moon: 'moon', panel: 'sidebar',
  chevrons: 'caret-up-down', clock: 'clock', users: 'users', filter: 'funnel',
  plus: 'plus', close: 'x', 'arrow-left': 'arrow-left', 'arrow-right': 'arrow-right',
  check: 'check', edit: 'pencil-simple', pause: 'pause', play: 'play', trash: 'trash', link: 'link',
};
const icons = {};
for (const [key, name] of Object.entries(names)) {
  const svg = await readFile(new URL(`node_modules/@phosphor-icons/core/assets/regular/${name}.svg`, root), 'utf8');
  const body = svg.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!body) throw new Error(`Invalid Phosphor SVG: ${name}`);
  icons[key] = body;
}
await writeFile(new URL('public/icons.js', root),
  '// Generated by scripts/icons.mjs from @phosphor-icons/core 2.1.1 (MIT).\n' +
  '// License: public/licenses/phosphor.txt\n' +
  `const phosphorIcons = Object.freeze(${JSON.stringify(icons, null, 2)});\n`);
await mkdir(new URL('public/licenses/', root), { recursive: true });
await copyFile(new URL('node_modules/@phosphor-icons/core/LICENSE', root), new URL('public/licenses/phosphor.txt', root));
console.log(`Updated ${Object.keys(icons).length} Phosphor icons.`);
